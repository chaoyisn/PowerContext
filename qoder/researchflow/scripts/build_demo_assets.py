def render_experiment_log_txt(payload: dict) -> str:
    lines = [
        "ResearchFlow demo - structured experiment record",
        "=" * 60,
        "",
        f"experiment_id : {payload['experiment_id']}",
        f"subject       : {payload['subject']}",
        f"conclusion    : {payload['conclusion']}",
        "",
        "[environment]",
    ]
    lines += [f"  {k} = {v}" for k, v in payload["environment"].items()]
    lines += ["", "[parameters]"]
    for key, value in payload["parameters"].items():
        lines.append(f"  {key} = {json.dumps(value, ensure_ascii=False)}")
    lines += ["", "[results]"]
    for row in payload["results"]:
        lines.append(f"  --- analyzer={row['analyzer']} verdict={row['verdict']} ---")
        lines += [f"    {k} = {v}" for k, v in row.items() if k not in {"analyzer", "verdict"}]
    lines.append("")
    return "\n".join(lines)


def build_pdf(path: Path) -> int:
    import fitz

    document = fitz.open()
    for page_lines in PDF_PAGES:
        page = document.new_page(width=595, height=842)  # A4 portrait
        body = "\n".join(page_lines)
        if body.strip():
            page.insert_textbox(
                fitz.Rect(56, 56, 539, 786),
                body,
                fontname="china-s",
                fontsize=11,
                align=0,
            )
    document.set_metadata(
        {
            "title": "seekdb Hybrid Retrieval Field Notes",
            "author": "ResearchFlow demo corpus",
            "subject": "seekdb v1.4.0.0 vector + fulltext + hybrid measurements",
            "creator": "scripts/build_demo_assets.py",
        }
    )
    document.save(path, deflate=True, garbage=3)
    page_count = document.page_count
    document.close()
    return page_count


def main() -> None:
    DEMO_DIR.mkdir(parents=True, exist_ok=True)

    pdf_path = DEMO_DIR / PDF_NAME
    pages = build_pdf(pdf_path)
    print(f"wrote {pdf_path.relative_to(PROJECT_ROOT)} ({pages} pages, page 4 intentionally blank)")

    plan_path = DEMO_DIR / "research_plan.md"
    plan_path.write_text(RESEARCH_PLAN_MD, encoding="utf-8", newline="\n")
    print(f"wrote {plan_path.relative_to(PROJECT_ROOT)}")

    payload = build_experiment_log()
    json_path = DEMO_DIR / "experiment_log.json"
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {json_path.relative_to(PROJECT_ROOT)}")

    txt_path = DEMO_DIR / "experiment_log.txt"
    txt_path.write_text(render_experiment_log_txt(payload), encoding="utf-8", newline="\n")
    print(f"wrote {txt_path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
